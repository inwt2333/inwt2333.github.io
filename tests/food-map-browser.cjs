const {chromium} = require('playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce'});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:8199/food.html');
    await page.locator('.memory').first().waitFor();
    const visible = async () => page.locator('.memory img').evaluateAll(images => images.map(image => image.getAttribute('src')));
    const first = await visible();
    assert.equal(first.length,3);
    assert.equal(new Set(first).size,3);
    await page.screenshot({path:'/tmp/food-map-desktop.png',fullPage:true});
    await page.locator('#board-shuffle').click();
    const second = await visible();
    assert.equal(second.length,3);
    assert.equal(second.filter(src => first.includes(src)).length,0);
    const title = await page.locator('.wall-sign h1').boundingBox();
    const board = await page.locator('#board').boundingBox();
    assert(title.x+title.width < board.x,'title hangs to the left of the photo board');
    await page.locator('#map-open').click();
    await page.locator('#food-map-dialog[open]').waitFor();
    await page.locator('#food-map.leaflet-container').waitFor();
    assert((await page.locator('.map-place-row').count())>=1);
    await page.locator('.map-place-row').first().click();
    await page.locator('.food-map-popup button').first().click();
    assert.equal(await page.locator('#receipt-dialog').evaluate(dialog=>dialog.open),true);
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(()=>document.activeElement.id),'map-open');
    await page.keyboard.press('Escape');
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'/tmp/food-map-mobile.png',fullPage:true});
    assert.equal(await page.locator('#board-shuffle').isVisible(),true);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.setViewportSize({width:320,height:568});
    await page.locator('#map-open').click();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:'/tmp/food-map-narrow.png',fullPage:true});
    await page.keyboard.press('Escape');
    const fallback = await browser.newPage();
    await fallback.route('**/assets/vendor/leaflet.js', route=>route.abort());
    await fallback.goto('http://127.0.0.1:8199/food.html');
    await fallback.locator('#map-open:enabled').waitFor();
    await fallback.locator('#map-open').click();
    assert.match(await fallback.locator('#food-map').innerText(),/地图暂时不可用/);
    await fallback.locator('.map-place-row').first().click();
    assert.equal(await fallback.locator('#receipt-dialog').evaluate(dialog=>dialog.open),true);
    await fallback.close();
    assert.deepEqual(errors,[]);
    console.log('PASS randomized wall, title placement, true map and mobile layout');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
