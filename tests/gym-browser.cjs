// Start a static server, then run: node tests/gym-browser.cjs
// Requires Playwright; PLAYWRIGHT_MODULE can point to an existing installation.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const base = process.env.GYM_TEST_URL || 'http://127.0.0.1:8198/gym/';
const output = process.env.GYM_SCREENSHOT_DIR;

(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
    const errors = [];
    const station = async id => {
      await page.locator(`[data-station="${id}"]`).focus();
      await page.keyboard.press('Enter');
      await page.waitForSelector('#detail-dialog[open]');
    };
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(base);
    await page.waitForFunction(() => document.querySelector('#scene-loading').hidden, {}, { timeout: 90000 });
    assert.equal(await page.locator('#scene-fallback').isVisible(), false);
    console.log('READY: room compiled');
    assert.equal(await page.locator('.scene-label,.site-header,.station-list,.journal-panel').count(), 0);
    assert.equal(await page.locator('#interaction-caption').isVisible(), false);
    assert.equal(await page.locator('#scene canvas').evaluate(c => c.clientWidth === innerWidth && c.clientHeight === innerHeight), true);
    const cleanFrame = await page.locator('canvas').first().screenshot();
    await page.mouse.move(740, 500);
    await page.waitForFunction(() => !document.querySelector('#interaction-caption').hidden);
    assert.match(await page.locator('#interaction-text').innerText(), /腹肌/);
    const hoverFrame = await page.locator('canvas').first().screenshot();
    assert.equal(cleanFrame.equals(hoverFrame), false, 'hover must change equipment pixels');
    await page.mouse.click(740, 500);
    await page.waitForSelector('#detail-dialog[open]');
    assert.match(await page.locator('#detail-title').innerText(), /腹肌/);
    await page.keyboard.press('Escape');
    await page.mouse.move(10, 10);
    await page.waitForFunction(() => document.querySelector('#interaction-caption').hidden);
    await station('row');
    await page.waitForSelector('#detail-dialog[open]');
    assert.equal(await page.locator('#detail-dialog').evaluate(d => d.open), true);
    assert.match(await page.locator('#detail-content').innerText(), /又一次，稳稳完成/);
    assert.equal(await page.locator('[data-body-view="back"]').isVisible(), true);
    assert.equal(await page.locator('[data-body-view="back"] .is-primary').count(), 2);
    await page.locator('[data-anatomy-view="front"]').click();
    assert.equal(await page.locator('[data-body-view="front"]').isVisible(), true);
    assert.equal(await page.locator('[data-body-view="back"]').isVisible(), false);
    assert.equal(await page.locator('[data-anatomy-view="front"]').getAttribute('aria-pressed'), 'true');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#detail-dialog').evaluate(d => d.open), false);
    await station('shoulder');
    assert.match(await page.locator('#detail-content').innerText(), /吃力/);
    assert.match(await page.locator('#detail-content').innerText(), /27 lb × 7 × 1/);
    await page.locator('#close-detail').click();

    await station('leg-curl');
    assert.equal(await page.locator('#detail-title').innerText(), '腿屈伸 / 腿弯曲');
    assert.match(await page.locator('.journal-records').innerText(), /27 lb × 12 × 2/);
    assert.equal(await page.locator('.history-group').count(), 1);
    await page.locator('[data-anatomy-view="back"]').click();
    assert.equal(await page.locator('[data-body-view="back"] [data-muscle="hamstrings"].is-primary').count(), 1);
    await page.locator('#close-detail').click();

    await page.keyboard.press('Escape');
    await page.waitForSelector('#menu-dialog[open]');
    await page.locator('#add-entry').click();
    await page.locator('#entry-form input[name="date"]').fill('2026-10-27');
    await page.locator('#entry-form input[name="weight"]').fill('30');
    await page.locator('#entry-form input[name="reps"]').fill('12');
    await page.locator('#entry-form input[name="sets"]').fill('');
    await page.locator('#entry-form textarea').fill('<img src=x onerror=alert(1)>');
    await page.locator('#entry-form button[type="submit"]').click();
    console.log('PASS: mouse and keyboard entry, menu and training form');
    await page.reload();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('inwt-gym-journal-v1')).entries.length), 1);
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('inwt-gym-journal-v1')).entries[0].loads[0].sets), 1);
    await station('row');
    assert.match(await page.locator('#detail-content').innerText(), /<img src=x onerror=alert\(1\)>/);
    assert.equal(await page.locator('#detail-content img').count(), 0);
    await page.locator('#detail-content [data-new]').click();
    await page.locator('#exercise-select').selectOption('cardio');
    assert.equal(await page.locator('#entry-form input[name="weight"]').isDisabled(), true);
    await page.locator('#entry-form input[name="date"]').fill('2026-10-27');
    await page.locator('#entry-form input[name="minutes"]').fill('15');
    await page.locator('#entry-form button[type="submit"]').click();
    await page.locator('#close-detail').click();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('inwt-gym-journal-v1')).entries[1].segments[0].minutes), 15);

    await station('weight');
    console.log('PASS: saved journal restored and cardio entered');
    assert.equal(await page.locator('.weight-chart').count(), 0);
    for (const [date, kg] of [['2026-10-26', '70'], ['2026-10-27', '69.8']]) {
      await page.locator('#weight-form input[name="date"]').fill(date);
      await page.locator('#weight-form input[name="kg"]').fill(kg);
      await page.locator('#weight-form button[type="submit"]').click();
    }
    assert.equal(await page.locator('.weight-chart').count(), 1);
    assert.equal(await page.locator('.weight-table tbody tr').count(), 2);
    await page.locator('#weight-form input[name="date"]').fill('2026-10-27');
    await page.locator('#weight-form input[name="kg"]').fill('69.9');
    await page.locator('#weight-form button[type="submit"]').click();
    assert.equal(await page.locator('.weight-table tbody tr').count(), 2);
    if (output) await page.screenshot({ path: `${output}/gym-weight.png`, fullPage: true });

    const downloadPromise = page.waitForEvent('download');
    await page.locator('#export-data').click();
    const download = await downloadPromise;
    const backup = JSON.parse(await fs.readFile(await download.path(), 'utf8'));
    assert.equal(backup.entries.length, 22);
    assert.equal(backup.weights.length, 2);
    const importPayload = { name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) };
    await page.locator('#import-file').setInputFiles(importPayload);
    await page.waitForFunction(() => document.querySelector('#toast').textContent.startsWith('备份已合并'));
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('inwt-gym-journal-v1')).entries.length), 2);
    await page.locator('#import-file').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{"version":1}') });
    await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('请选择本训练馆'));
    await page.evaluate(() => { location.hash = 'calendar'; });
    await page.waitForSelector('#detail-dialog[open]');
    await page.locator('[data-day="2026-10-22"]').click();
    assert.match(await page.locator('#detail-content').innerText(), /吃力/);
    await page.locator('[data-month="-1"]').click();
    assert.match(await page.locator('#detail-content').innerText(), /还没有训练记录/);
    await page.locator('#close-detail').click();
    await station('row');
    await page.locator('[data-delete]').click();
    await page.locator('#close-detail').click();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('inwt-gym-journal-v1')).entries.length), 1);
    console.log('PASS: 3D entry, nested dialogs, source fidelity, persistence, cardio, weights, safe text, backup merge, calendar and deletion');

    await page.mouse.move(10, 10);
    await page.keyboard.press('Escape');
    await page.waitForSelector('#menu-dialog[open]');
    await page.locator('#reset-view').click();
    const startFrame = await page.locator('canvas').first().screenshot();
    await page.mouse.move(650, 350);
    await page.mouse.down();
    await page.mouse.move(790, 390, { steps: 8 });
    await page.mouse.up();
    assert.equal(await page.locator('#detail-dialog').evaluate(d => d.open), false, 'drag must not open a record');
    const turned = await page.locator('canvas').first().screenshot();
    assert.equal(startFrame.equals(turned), false, 'drag must turn the camera');
    await page.keyboard.down('KeyW');
    await page.waitForTimeout(250);
    await page.keyboard.up('KeyW');
    const moved = await page.locator('canvas').first().screenshot();
    assert.equal(turned.equals(moved), false, 'W must move through the room');
    await page.keyboard.press('Escape');
    await page.waitForSelector('#menu-dialog[open]');
    await page.locator('#reset-view').click();
    await page.mouse.move(10, 10);
    await page.waitForTimeout(200);
    const reset = await page.locator('canvas').first().screenshot();
    assert.equal(startFrame.equals(reset), true, 'reset must restore the entrance');
    console.log('PASS: immersive canvas, geometry hover, captions, direct raycast, camera drag, walking, reset and pause menu');
    await page.evaluate(() => localStorage.clear());
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#scene-loading').hidden, {}, { timeout: 90000 });
    for (const width of [320, 390, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: width < 600 ? 844 : 1000 });
      await page.waitForFunction(() => document.querySelector('#scene canvas').clientWidth === innerWidth);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `overflow at ${width}`);
      assert.equal(await page.locator('#scene-fallback').isVisible(), false);
      await station('weight');
      assert.equal(await page.locator('#detail-dialog').evaluate(d => d.scrollWidth > d.clientWidth), false, `dialog overflow at ${width}`);
      await page.keyboard.press('Escape');
      if (output && [390, 1440].includes(width)) await page.screenshot({ path: `${output}/gym-${width}.png`, fullPage: true });
    }
    console.log('PASS: desktop, tablet and mobile layouts at 320 / 390 / 768 / 1024 / 1440 px');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#scene-loading').hidden, {}, { timeout: 90000 });
    assert.equal(await page.locator('#scene-fallback').isVisible(), false);

    const fallback = await browser.newPage();
    await fallback.route('**/room.mjs*', route => route.abort());
    await fallback.goto(base);
    await fallback.waitForSelector('#scene-fallback', { state: 'visible' });
    await fallback.locator('#fallback-stations a[href="#row"]').click();
    await fallback.waitForSelector('#detail-dialog[open]');
    assert.match(await fallback.locator('#detail-content').innerText(), /坐姿划船/);
    await fallback.close();
    const blocked = await browser.newPage();
    await blocked.addInitScript(() => { Storage.prototype.setItem = () => { throw new DOMException('blocked', 'SecurityError'); }; });
    await blocked.goto(`${base}#weight`);
    await blocked.locator('#weight-form input[name="kg"]').fill('70');
    await blocked.locator('#weight-form button[type="submit"]').click();
    assert.match(await blocked.locator('#weight-error').innerText(), /保存失败/);
    assert.equal(await blocked.locator('.weight-table').count(), 0);
    await blocked.close();
    assert.deepEqual(errors, []);
    console.log('PASS: reduced motion, unavailable 3D fallback, blocked storage, no uncaught errors');
    await page.locator('.room-home').click();
    await page.waitForURL('**/index.html');
    const gymLink = page.locator('a.station[href="gym/"]');
    await gymLink.click();
    await page.waitForURL('**/gym/');
    assert.equal(await page.locator('.room-home').getAttribute('href'), '../index.html');
    console.log('PASS: metro homepage entrance and return link');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
